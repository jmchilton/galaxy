"""Render the spec cases, access patterns, rules and uncheckable codes as the Markdown section of the admin docs.

``python -m galaxy.tool_util.security.spec.docs`` prints the section.
"""

from collections.abc import (
    Callable,
    Collection,
    Mapping,
    Sequence,
)
from typing import TypeVar

import yaml

from galaxy.tool_util.parser import get_tool_source
from galaxy.tool_util.security import (
    patterns,
    rules,
)
from galaxy.tool_util.security.classify import (
    DESCRIPTIONS as UNCHECKABLE_DESCRIPTIONS,
    Uncheckable,
)
from galaxy.tool_util.security.spec import (
    load_cases,
    SpecCase,
    tool_path,
)

Code = TypeVar("Code", bound=str)

BEGIN = "<!-- BEGIN spec cases, generated by `python -m galaxy.tool_util.security.spec.docs` -->"
END = "<!-- END spec cases -->"


def spec_cases_markdown(cases: dict[str, SpecCase]) -> str:
    lines = [BEGIN, ""]
    for case_id, case in cases.items():
        lines += _case(case_id, case)
    lines += _patterns(cases)
    lines += _rules(cases)
    lines += _uncheckable(cases)
    lines.append(END)
    return "\n".join(lines) + "\n"


def _patterns(cases: dict[str, SpecCase]) -> list[str]:
    lines = [
        "## Access patterns",
        "",
        "The review also reports reads it cannot follow to a value of a tool input. A read by name (reflection)",
        "can write any value without a finding about it.",
        "",
    ]
    groups = (
        ("Reads the review cannot follow", [c for c in patterns.PatternCode if c not in patterns.SERVER_VALUES]),
        ("Reads of values the server sets", [c for c in patterns.PatternCode if c in patterns.SERVER_VALUES]),
    )
    return lines + _described(groups, patterns.DESCRIPTIONS, cases, lambda case: case.review.patterns)


def _rules(cases: dict[str, SpecCase]) -> list[str]:
    lines = ["## Rules", "", "Each finding has one of these rules.", ""]
    groups = (
        ("Vulnerabilities", [r for r in rules.Rule if r in rules.VULNERABILITY_RULES]),
        ("Capabilities", [r for r in rules.Rule if r not in rules.VULNERABILITY_RULES]),
    )
    return lines + _described(groups, rules.DESCRIPTIONS, cases, lambda case: case.review.rules)


def _uncheckable(cases: dict[str, SpecCase]) -> list[str]:
    lines = [
        "## Uncheckable codes",
        "",
        "Where a template writes values that no character test of a finding can judge (the classified unchecked",
        "locations, `uncheckable_locations` in the CLI's JSON), only a check that every value is plain could vet a",
        "job. `classify()` and the CLI give these codes when not even that could: the review cannot decide the tool",
        "from its templates. A template the review did not analyse is unchecked but gets no code of its own, so",
        "`--fail-on uncheckable` lets it through and `--fail-on unchecked` does not.",
        "",
    ]
    groups = (("Codes", list(Uncheckable)),)
    return lines + _described(groups, UNCHECKABLE_DESCRIPTIONS, cases, lambda case: case.review.codes or [])


def _described(
    groups: Sequence[tuple[str, Sequence[Code]]],
    descriptions: Mapping[Code, str],
    cases: dict[str, SpecCase],
    codes_of: Callable[[SpecCase], Collection[str]],
) -> list[str]:
    lines = []
    for title, codes in groups:
        lines += [f"### {title}", ""]
        for code in codes:
            lines += [f"#### `{code}`", "", descriptions[code], ""]
            shown = [case_id for case_id, case in cases.items() if code in codes_of(case)]
            if shown:
                lines += [f"Cases: {', '.join(f'`{case_id}`' for case_id in shown)}.", ""]
    return lines


def _case(case_id: str, case: SpecCase) -> list[str]:
    command = (get_tool_source(tool_path(case.tool)).parse_command() or "").strip()
    review = case.review.model_dump(mode="json", exclude_defaults=True)
    lines = [f"### {case_id}", "", case.doc, "", f"Tool `{case.tool}`:", "", "```", command, "```", ""]
    if review:
        rendered = yaml.safe_dump(review, sort_keys=False, allow_unicode=True, width=1000).rstrip()
        lines += ["Review:", "", "```", rendered, "```", ""]
    return lines


if __name__ == "__main__":
    print(spec_cases_markdown(load_cases()), end="")
