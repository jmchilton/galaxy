"""Render the refusal codes, the access patterns and their spec cases as the Markdown section of the admin docs.

``python -m galaxy.tool_util.security.spec.docs`` prints the section.
"""

from typing import (
    Dict,
    List,
)

import yaml

from galaxy.tool_util.parser import get_tool_source
from galaxy.tool_util.security import patterns
from galaxy.tool_util.security.codes import (
    DESCRIPTIONS,
    RefusalCode,
)
from galaxy.tool_util.security.spec import (
    JobCase,
    load_cases,
    SpecCase,
    tool_path,
)

BEGIN = "<!-- BEGIN refusal codes, generated by `python -m galaxy.tool_util.security.spec.docs` -->"
END = "<!-- END refusal codes -->"


def refusal_codes_markdown(cases: Dict[str, SpecCase]) -> str:
    lines = [BEGIN, ""]
    for code in RefusalCode:
        lines += [f"### `{code.value}`", "", DESCRIPTIONS[code], ""]
        for case_id, case in cases.items():
            if case.code == code:
                lines += _case(case_id, case)
    lines += [
        "### Jobs that run",
        "",
        "Values the review lets through, where a check that is too strict would refuse common names.",
        "",
    ]
    for case_id, case in cases.items():
        if case.code is None and not case.review.patterns:
            lines += _case(case_id, case)
    lines += _patterns(cases)
    lines.append(END)
    return "\n".join(lines) + "\n"


def _patterns(cases: Dict[str, SpecCase]) -> List[str]:
    lines = [
        "## Access patterns",
        "",
        "The review also reports reads it cannot follow to a value of the job. Where a template writes a value",
        "read by name (reflection), the strict check reads every value the job carries; where it writes one of",
        "the dataset model or the user object, every value of its input, or of the job. A read of data the job",
        "does not carry refuses every job of the tool the review cannot check otherwise. A case marked as a",
        "known bypass is a tool whose jobs run whatever their values.",
        "",
    ]
    groups = (
        ("Reads the job check cannot see", [c for c in patterns.PatternCode if c not in patterns.SERVER_VALUES]),
        ("Reads of values the server sets", [c for c in patterns.PatternCode if c in patterns.SERVER_VALUES]),
    )
    for title, codes in groups:
        lines += [f"### {title}", ""]
        for code in codes:
            lines += [f"#### `{code.value}`", "", patterns.DESCRIPTIONS[code], ""]
            shown = [case_id for case_id, case in cases.items() if code in case.review.patterns]
            if refused := [case_id for case_id in shown if cases[case_id].code is not None]:
                lines += [f"Refused cases with it: {', '.join(f'`{case_id}`' for case_id in refused)}.", ""]
            for case_id in shown:
                if cases[case_id].code is None:
                    lines += _case(case_id, cases[case_id], level="#####")
    return lines


def _case(case_id: str, case: SpecCase, level: str = "####") -> List[str]:
    command = (get_tool_source(tool_path(case.tool)).parse_command() or "").strip()
    lines = [f"{level} {case_id}", "", case.doc, "", f"Tool `{case.tool}`:", "", "```", command, "```", ""]
    for color, jobs in (("Refused", case.red), ("Runs", case.green)):
        for job in jobs:
            title = f"{color}{': ' + job.doc if job.doc else ''}"
            lines += [title, "", "```", _context(job).rstrip(), "```", ""]
    return lines


def _context(job: JobCase) -> str:
    context = job.model_dump(mode="json", exclude_defaults=True, exclude={"doc", "expect", "harm"})
    return yaml.safe_dump(context, sort_keys=False, allow_unicode=True) if context else "{}\n"


if __name__ == "__main__":
    print(refusal_codes_markdown(load_cases()), end="")
