// Generate TypeScript types from Galaxy's OpenAPI schema.
//
// openapi-typescript marks properties with a default as required, which is right for
// responses (the server always sends them) but wrong for request bodies (the server
// fills them in). It already exempts inline request bodies; Galaxy's are $refs into
// components/schemas, so schemas reachable only from request bodies are exempted here.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";

import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import { parse } from "yaml";

const SCHEMA_PREFIX = "#/components/schemas/";
const PROPERTY_PATH = /^#\/components\/schemas\/([^/]+)\/([^/]+)$/;
const BANNER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

function unescapePointer(segment) {
    return segment.replaceAll("~1", "/").replaceAll("~0", "~");
}

function collectRefs(node, refs) {
    if (Array.isArray(node)) {
        node.forEach((item) => collectRefs(item, refs));
    } else if (node && typeof node === "object") {
        if (typeof node.$ref === "string" && node.$ref.startsWith(SCHEMA_PREFIX)) {
            refs.add(node.$ref.slice(SCHEMA_PREFIX.length));
        }
        Object.values(node).forEach((value) => collectRefs(value, refs));
    }
    return refs;
}

function reachable(schemas, seeds) {
    const seen = new Set();
    const stack = [...seeds];
    while (stack.length) {
        const name = stack.pop();
        if (seen.has(name) || !schemas[name]) {
            continue;
        }
        seen.add(name);
        stack.push(...collectRefs(schemas[name], new Set()));
    }
    return seen;
}

function requestOnlySchemaNames(document) {
    const schemas = document.components?.schemas ?? {};
    const requestSeeds = new Set();
    const responseSeeds = new Set();
    for (const operations of Object.values(document.paths ?? {})) {
        for (const operation of Object.values(operations)) {
            collectRefs(operation?.requestBody, requestSeeds);
            collectRefs(operation?.responses, responseSeeds);
        }
    }
    const responseSchemas = reachable(schemas, responseSeeds);
    return new Set([...reachable(schemas, requestSeeds)].filter((name) => !responseSchemas.has(name)));
}

export async function generateApiSchema(document) {
    const schemas = document.components?.schemas ?? {};
    const requestOnlySchemas = requestOnlySchemaNames(document);
    const ast = await openapiTS(document, {
        silent: true,
        transformProperty(property, schemaObject, options) {
            const match = options.path?.match(PROPERTY_PATH);
            if (!match || property.questionToken || !("default" in schemaObject)) {
                return undefined;
            }
            const [schemaName, propertyName] = [match[1], match[2]].map(unescapePointer);
            if (!requestOnlySchemas.has(schemaName) || schemas[schemaName].required?.includes(propertyName)) {
                return undefined;
            }
            return ts.factory.updatePropertySignature(
                property,
                property.modifiers,
                property.name,
                ts.factory.createToken(ts.SyntaxKind.QuestionToken),
                property.type,
            );
        },
    });
    return BANNER + astToString(ast);
}

if (process.argv[1] && realpathSync(process.argv[1]) === import.meta.filename) {
    const [input, output] = process.argv.slice(2);
    if (!input || !output) {
        console.error("usage: generate-api-schema.mjs <openapi.yaml> <schema.ts>");
        process.exit(1);
    }
    writeFileSync(output, await generateApiSchema(parse(readFileSync(input, "utf8"))));
}
